-- Create conversations table
create table public.conversations (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  user1_id uuid references public.profiles(id) on delete cascade not null,
  user2_id uuid references public.profiles(id) on delete cascade not null
);

-- Unique index to prevent duplicate conversations between same two users
create unique index conversations_user1_user2_idx on public.conversations (
  least(user1_id, user2_id),
  greatest(user1_id, user2_id)
);

-- Enable RLS for conversations
alter table public.conversations enable row level security;

create policy "Users can view their own conversations." on public.conversations
  for select using (auth.uid() = user1_id or auth.uid() = user2_id);

create policy "Users can start a conversation." on public.conversations
  for insert with check (auth.uid() = user1_id or auth.uid() = user2_id);


-- Create messages table
create table public.messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint references public.conversations(id) on delete cascade not null,
  sender_id uuid references public.profiles(id) on delete cascade not null,
  message_text text,
  is_exchange_card boolean default false not null,
  exchange_book_title text,
  exchange_status text, -- 'Requested' | 'Accepted' | 'Declined' | 'Completed'
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS for messages
alter table public.messages enable row level security;

create policy "Users can view messages in their conversations." on public.messages
  for select using (
    exists (
      select 1 from public.conversations c
      where c.id = conversation_id 
      and (c.user1_id = auth.uid() or c.user2_id = auth.uid())
    )
  );

create policy "Users can send messages to their conversations." on public.messages
  for insert with check (
    auth.uid() = sender_id 
    and exists (
      select 1 from public.conversations c
      where c.id = conversation_id 
      and (c.user1_id = auth.uid() or c.user2_id = auth.uid())
    )
  );

create policy "Users can update exchange statuses in their conversations." on public.messages
  for update using (
    exists (
      select 1 from public.conversations c
      where c.id = conversation_id 
      and (c.user1_id = auth.uid() or c.user2_id = auth.uid())
    )
  );


-- Create view_messages to resolve chat details dynamically
create or replace view public.view_messages as
select 
  m.*,
  coalesce(
    case when c.user1_id = auth.uid() then p2.name else p1.name end,
    'Other Reader'
  ) as "chatId",
  case when m.sender_id = auth.uid() then 'me'::text else 'other'::text end as "sender",
  (extract(epoch from m.created_at) * 1000)::bigint as "timestamp"
from public.messages m
join public.conversations c on m.conversation_id = c.id
left join public.profiles p1 on c.user1_id = p1.id
left join public.profiles p2 on c.user2_id = p2.id;


-- Create view_recent_chats to fetch inbox feed
create or replace view public.view_recent_chats as
with conversation_lasts as (
  select distinct on (conversation_id)
    *
  from public.messages
  order by conversation_id, created_at desc
)
select 
  cl.id as "messageId",
  c.id as "conversationId",
  coalesce(
    case when c.user1_id = auth.uid() then p2.name else p1.name end,
    'Other Reader'
  ) as "chatId",
  cl.message_text as "messageText",
  (extract(epoch from cl.created_at) * 1000)::bigint as "timestamp",
  cl.is_exchange_card as "isExchangeCard",
  cl.exchange_book_title as "exchangeBookTitle",
  cl.exchange_status as "exchangeStatus",
  case when cl.sender_id = auth.uid() then 'me'::text else 'other'::text end as "sender"
from conversation_lasts cl
join public.conversations c on cl.conversation_id = c.id
left join public.profiles p1 on c.user1_id = p1.id
left join public.profiles p2 on c.user2_id = p2.id
where c.user1_id = auth.uid() or c.user2_id = auth.uid();
