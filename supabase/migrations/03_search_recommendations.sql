-- Create events table
create table public.events (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  title text not null,
  category text not null, -- 'Poetry Circles' | 'Book Exchange' | 'Book Fairs' | 'Reading Clubs'
  date text not null,     -- formatted e.g. 'Aug 15, 2026'
  time text not null,     -- formatted e.g. '6:00 PM'
  location text not null,
  organizer text not null,
  description text not null
);

-- Enable RLS for events
alter table public.events enable row level security;

create policy "Events are viewable by everyone." on public.events
  for select using (true);

create policy "Authenticated users can create events for testing." on public.events
  for insert with check (auth.role() = 'authenticated');


-- Create event_rsvps table (junction for tracking event RSVPs)
create table public.event_rsvps (
  event_id bigint references public.events(id) on delete cascade not null,
  profile_id uuid references public.profiles(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  primary key (event_id, profile_id)
);

-- Enable RLS for event_rsvps
alter table public.event_rsvps enable row level security;

create policy "Event RSVPs are viewable by everyone." on public.event_rsvps
  for select using (true);

create policy "Users can RSVP to an event." on public.event_rsvps
  for insert with check (auth.uid() = profile_id);

create policy "Users can cancel their RSVP." on public.event_rsvps
  for delete using (auth.uid() = profile_id);


-- Create view_events to join RSVPs dynamically
create or replace view public.view_events as
select 
  e.*,
  (select count(*) > 0 from public.event_rsvps er where er.event_id = e.id and er.profile_id = auth.uid()) as "isRsvped"
from public.events e;


-- Create view_readers to list other readers near the current user
create or replace view public.view_readers as
select 
  abs(hashtext(p.id::text)) as id,
  p.id as uuid,
  p.name,
  p.bio,
  p.location,
  p.reading_score as "readingScore",
  (
    'Owned: ' || (select count(*)::text from public.books b where b.owner_id = p.id) || 
    ' | Read: ' || (select count(*)::text from public.books b where b.owner_id = p.id and b.is_read = true)
  ) as stats,
  p.genres,
  p.goals,
  p.verification_status as "verificationBadge",
  (75 + (abs(hashtext(p.id::text || coalesce(auth.uid()::text, ''))) % 25)) as "matchPercentage"
from public.profiles p
where p.id != auth.uid();
