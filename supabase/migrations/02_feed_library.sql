-- Create view_books to join profile info and dynamic like metrics
create or replace view public.view_books as
select 
  b.*,
  p.name as "ownerName",
  (select count(*)::int from public.book_likes bl where bl.book_id = b.id) as "likesCount",
  (select count(*) > 0 from public.book_likes bl where bl.book_id = b.id and bl.profile_id = auth.uid()) as "isLiked",
  (b.owner_id = auth.uid()) as "isOwned"
from public.books b
left join public.profiles p on b.owner_id = p.id;


-- Create view_stories to join profile info and dynamic like metrics
create or replace view public.view_stories as
select 
  s.*,
  p.name as "authorName",
  (select count(*)::int from public.story_likes sl where sl.story_id = s.id) as "likesCount",
  (select count(*) > 0 from public.story_likes sl where sl.story_id = s.id and sl.profile_id = auth.uid()) as "isLiked",
  (s.profile_id = auth.uid()) as "isUserStory"
from public.reading_stories s
left join public.profiles p on s.profile_id = p.id;
