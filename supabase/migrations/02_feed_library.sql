create policy "Users can insert their own reading stories." on public.reading_stories
  for insert with check (auth.uid() = profile_id);

create policy "Users can delete their own reading stories." on public.reading_stories
  for delete using (auth.uid() = profile_id);


-- Create story_likes table (junction for story likes)
create table public.story_likes (
  story_id bigint references public.reading_stories(id) on delete cascade not null,
  profile_id uuid references public.profiles(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  primary key (story_id, profile_id)
