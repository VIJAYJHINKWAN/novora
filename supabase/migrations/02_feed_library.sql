-- Create books table
create table public.books (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  owner_id uuid references public.profiles(id) on delete cascade not null,
  title text not null,
  author text not null,
  genre text not null,
  summary text,
  rating numeric default 4.5 not null,
  is_read boolean default false not null,
  is_wishlist boolean default false not null,
  is_exchangeable boolean default false not null,
  is_lendable boolean default false not null,
  cover_res_id integer default 1 not null,
  owner_distance text default '0.5 miles away' not null,
  owner_rating numeric default 5.0 not null
);

-- Enable RLS for books
alter table public.books enable row level security;

create policy "Books are viewable by everyone." on public.books
  for select using (true);

create policy "Users can insert their own books." on public.books
  for insert with check (auth.uid() = owner_id);

create policy "Users can update their own books." on public.books
  for update using (auth.uid() = owner_id);

create policy "Users can delete their own books." on public.books
  for delete using (auth.uid() = owner_id);


-- Create book_likes table (junction for book likes)
create table public.book_likes (
  book_id bigint references public.books(id) on delete cascade not null,
  profile_id uuid references public.profiles(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  primary key (book_id, profile_id)
);

-- Enable RLS for book_likes
alter table public.book_likes enable row level security;

create policy "Book likes are viewable by everyone." on public.book_likes
  for select using (true);

create policy "Users can like a book." on public.book_likes
  for insert with check (auth.uid() = profile_id);

create policy "Users can unlike a book." on public.book_likes
  for delete using (auth.uid() = profile_id);


-- Create reading_stories table (Reading Notes & Spotlights)
create table public.reading_stories (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  profile_id uuid references public.profiles(id) on delete cascade not null,
  book_title text not null,
  note_text text not null,
  story_type text default 'Current Read' not null,
  background_theme text default 'Cozy Cafe' not null
